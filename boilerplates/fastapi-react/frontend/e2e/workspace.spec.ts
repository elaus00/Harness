import { test, expect } from '@playwright/test'

test('가입, 업무 관리, 세션 복구, 모바일 탐색, 로그아웃', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '다시 만나서 반가워요' })).toBeVisible()
  await page.screenshot({ path: '../artifacts/login.png', fullPage: true })
  await page.getByRole('button', { name: '계정 만들기', exact: true }).click()
  await page.getByLabel('이름', { exact: true }).fill('이로운')
  await page.getByLabel('이메일', { exact: true }).fill(`hello-${Date.now()}@example.com`)
  const email = await page.getByLabel('이메일', { exact: true }).inputValue()
  await page.getByLabel('비밀번호', { exact: true }).fill('strong-test-password-123')
  await page.getByRole('button', { name: '계정 만들기', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: '대시보드', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '샘플 업무 불러오기' }).click()
  await expect(page.getByRole('cell', { name: /세션 회고 워크플로우 개선/ })).toBeVisible()
  await page.getByRole('button', { name: '만들기', exact: true }).click()
  await page.getByLabel('업무 제목').fill('브라우저에서 만든 업무')
  await page.getByRole('button', { name: '업무 만들기', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('cell', { name: /브라우저에서 만든 업무/ })).toBeVisible()
  await page.getByLabel('브라우저에서 만든 업무 상태').selectOption('done')
  await expect(page.getByLabel('브라우저에서 만든 업무 상태')).toHaveValue('done')
  await page.getByLabel('업무 검색').fill('브라우저에서')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('업무 검색').fill('없는 업무 검색')
  await expect(page.getByText('조건에 맞는 업무가 없습니다')).toBeVisible()
  await page.getByLabel('업무 검색').fill('')
  await page.reload()
  await expect(page.getByLabel('브라우저에서 만든 업무 상태')).toHaveValue('done')
  await expect(page.locator('html')).toHaveAttribute('data-color-mode', 'light')
  await page.screenshot({ path: '../artifacts/dashboard.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: '메뉴 열기' })).toBeVisible()
  await page.getByRole('button', { name: '메뉴 열기' }).click()
  await page.getByRole('button', { name: /내 업무/ }).click()
  await expect(page.getByRole('heading', { name: '내 업무' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../artifacts/mobile.png', fullPage: true })
  await page.getByRole('button', { name: '메뉴 열기' }).click()
  await page.getByRole('button', { name: '로그아웃', exact: true }).click()
  await expect(page.getByRole('heading', { name: '다시 만나서 반가워요' })).toBeVisible()
  await page.getByLabel('이메일', { exact: true }).fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('이메일 또는 비밀번호')
  await page.getByLabel('비밀번호', { exact: true }).fill('strong-test-password-123')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page.getByRole('heading', { name: '대시보드', exact: true })).toBeVisible()
  expect(pageErrors).toEqual([])
})
